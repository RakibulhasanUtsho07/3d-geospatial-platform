import path from "node:path";

const SHA256 = /^[a-f0-9]{64}$/i;
const RELEASE_FLAGS = [
  "acceptanceEligible",
  "publicationEligible",
  "mapReady",
  "automaticApproval",
];
const REVIEW_ONLY_FLAGS = [
  "candidateGeometryValidated",
  "independentReferenceVerified",
  "heldOutCheckpointAccuracyVerified",
];

function object(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
function equalPath(a, b) {
  return path.resolve(a) === path.resolve(b);
}
function within(parent, child) {
  const relative = path.relative(path.resolve(parent), path.resolve(child));
  return relative !== "" && relative !== ".." &&
    !relative.startsWith(".." + path.sep) && !path.isAbsolute(relative);
}

/**
 * Validate the binding between a BRF-24 candidate-generation authorization,
 * the candidate GLB bytes, and the independent-truth extraction config.
 *
 * This is deliberately a review-only gate: success permits geometry evaluation,
 * never model acceptance, publication, map readiness, or automatic approval.
 */
export function assessBrf25CandidateBinding(input = {}) {
  const checks = [];
  const blockers = [];
  const record = input.authorization;
  const check = (id, passed, detail) => {
    checks.push({ id, status: passed ? "passed" : "blocked", detail });
    if (!passed) blockers.push({ id, detail });
  };

  check("authorization-record-present", object(record),
    object(record) ? "A parsed BRF-24 authorization record is present." : "Authorization record is missing or not an object.");
  if (!object(record)) {
    return { ready: false, status: "blocked", checks, blockers };
  }

  check("authorization-schema", record.schemaVersion === "1.0.0" &&
    record.recordType === "brf-24-colmap-execution-authorization",
  "The record must use the BRF-24 authorization schema and record type.");
  check("candidate-generated", record.status === "candidate-generated-requires-review" &&
    record.candidateGlbGenerated === true && object(record.candidateGlb),
  "Only an actual worker-generated candidate marked for review can enter geometry evaluation.");
  const reviewer = record.humanDecision?.reviewer;
  const reviewerValid = (typeof reviewer === "string" && reviewer.trim().length > 0) ||
    (object(reviewer) && typeof reviewer.name === "string" && reviewer.name.trim().length > 0 &&
      typeof reviewer.identifier === "string" && reviewer.identifier.trim().length > 0);
  check("reviewer-disposition", record.humanDecision?.overallDisposition === "continue-to-reconstruction-preflight" &&
    reviewerValid && SHA256.test(record.humanDecision?.sha256 ?? ""),
  "A hash-bound human decision with reviewer name/identifier and the permitted continuation disposition is required.");
  check("preflight-hash-pinned", SHA256.test(record.preflightReport?.sha256 ?? ""),
    "Authorization must pin the hash of its BRF-23 preflight report.");
  check("profile-hash-pinned", SHA256.test(record.profile?.sha256 ?? ""),
    "Authorization must pin the exact BRF-23 profile hash.");
  check("toolchain-rechecked", record.toolchain?.name === "COLMAP" &&
    typeof record.toolchain.version === "string" &&
    record.toolchain.versionRecheckedImmediatelyBeforeRun === true,
  "The exact COLMAP version must have been rechecked immediately before the reconstruction attempt.");
  check("local-frame-policy", object(record.coordinateFrame) &&
    typeof record.coordinateFrame.policy === "string" &&
    record.coordinateFrame.policy.length > 0 &&
    record.coordinateFrame.registrationToGps !== true,
  "Coordinate-frame policy must be explicit and must not claim unverified GPS registration.");
  check("review-only-invariants", [...RELEASE_FLAGS, ...REVIEW_ONLY_FLAGS].every((key) => record[key] === false) &&
    record.scaleCalibration?.status === "not-calibrated",
  "Geometry evaluation must start before independent geometry is verified, with every release flag false and no survey scale claimed.");

  const workspaceRoot = input.workspaceRoot;
  const candidateRel = record.candidateGlb?.relativePath;
  const candidateSha = input.candidateSha256;
  const candidateByteSize = input.candidateByteSize;
  const expectedGlbSha256 = input.expectedGlbSha256;
  check("candidate-relative-path", typeof candidateRel === "string" && candidateRel.trim().length > 0 &&
    !path.isAbsolute(candidateRel) && within(workspaceRoot, path.resolve(workspaceRoot, candidateRel)),
  "The authorized candidate path must be relative to and contained within the selected workspace.");
  if (typeof candidateRel === "string" && candidateRel.trim() && workspaceRoot) {
    check("configured-candidate-path", typeof input.configuredCandidatePath === "string" &&
      equalPath(path.resolve(workspaceRoot, candidateRel), input.configuredCandidatePath),
    "The truth-evaluation config must point to the exact GLB generated by the authorized worker.");
  } else {
    check("configured-candidate-path", false, "Cannot bind the configured candidate path without a valid workspace-relative candidate path.");
  }

  check("actual-candidate-sha256", SHA256.test(candidateSha ?? "") &&
    candidateSha?.toLowerCase() === record.candidateGlb?.sha256?.toLowerCase(),
  "The GLB's current byte hash must match the generated-candidate hash in BRF-24 authorization.");
  check("config-candidate-sha256", SHA256.test(expectedGlbSha256 ?? "") &&
    expectedGlbSha256?.toLowerCase() === candidateSha?.toLowerCase(),
  "The independent-truth config must pin the exact current candidate GLB hash.");
  check("candidate-byte-size", Number.isSafeInteger(candidateByteSize) && candidateByteSize > 0 &&
    candidateByteSize === record.candidateGlb?.byteSize,
  "The candidate GLB's current byte size must match the worker's authorization record.");

  const selected = record.selectedSourceImages;
  check("selected-source-hashes", Array.isArray(selected) && selected.length >= 3 &&
    selected.every((item) => object(item) && SHA256.test(item.sha256 ?? "")),
  "The authorization must retain at least three selected source images bound by SHA-256.");

  return {
    ready: blockers.length === 0,
    status: blockers.length === 0 ? "candidate-bound-review-only" : "blocked",
    checks,
    blockers,
    binding: blockers.length === 0 ? {
      candidateGlbSha256: candidateSha.toLowerCase(),
      candidateByteSize,
      workspaceRelativePath: candidateRel,
      humanDecisionSha256: record.humanDecision.sha256.toLowerCase(),
      preflightSha256: record.preflightReport.sha256.toLowerCase(),
      profileSha256: record.profile.sha256.toLowerCase(),
      colmapVersion: record.toolchain.version,
      coordinateFramePolicy: record.coordinateFrame.policy,
    } : null,
  };
}
