#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { generateBuildingModel } from "../src/core/building-generation/generation-engine.mjs";

const root = process.cwd();
const specPath = path.resolve(root, process.argv[2] ?? "data/heritage/bangabhaban-building-spec.json");
const modelPath = path.resolve(root, process.argv[3] ?? "data/heritage/generated/bangabhaban-candidate.glb");
const reportPath = modelPath.replace(/\.glb$/i, ".report.json");
if (!modelPath.toLowerCase().endsWith(".glb")) throw new TypeError("output path must end in .glb");
const rawSpec = JSON.parse(await readFile(specPath, "utf8"));
const { glb, normalizedSpec, report } = generateBuildingModel(rawSpec);
await mkdir(path.dirname(modelPath), { recursive: true });
await writeFile(modelPath, glb);
const sha256 = createHash("sha256").update(glb).digest("hex");
const candidate = {
  schemaVersion: "1.0.0",
  generatedAt: new Date().toISOString(),
  status: "candidate-generated-review-required",
  engine: report.engine,
  building: {
    id: normalizedSpec.id,
    name: "Bangabhaban",
    location: normalizedSpec.location,
    footprint: {
      areaM2: normalizedSpec.footprint.areaM2,
      perimeterM: normalizedSpec.footprint.perimeterM,
      geometryStatus: "estimated-rectangle-not-survey-traced"
    },
    dimensions: normalizedSpec.dimensions,
    architecture: normalizedSpec.architecture
  },
  model: {
    path: path.relative(root, modelPath).split(path.sep).join("/"),
    bytes: glb.byteLength,
    sha256,
    format: "glb",
    textureStatus: "untextured-procedural-materials-only"
  },
  evidence: normalizedSpec.evidence,
  sourceProvenance: normalizedSpec.sources,
  geometryQA: report.geometryQuality,
  generationReport: report,
  gates: {
    glbGenerated: true,
    structuralGeometryQACompleted: true,
    independentMeasuredFootprintVerified: false,
    heightAndDimensionsIndependentlyVerified: false,
    facadeReviewedAgainstReferences: false,
    textureUVQACompleted: false,
    deterministicThirteenViewReviewCompleted: false,
    georeferenceSurveyVerified: false,
    mapReady: false,
    publicationEligible: false,
    humanReviewRequired: true
  },
  limitations: [
    "This is a procedural candidate generated by the repository's Building Generation Engine; reference images are stored as provenance and are not automatically interpreted by the generator.",
    "The 44 m x 21 m rectangular footprint is an explicit estimate chosen to approximate the published PWD plinth-area figure; it is not a traced/surveyed footprint.",
    "Dome and arcade proportions are visual estimates; hidden elevations, exact dimensions, and detailed mouldings are unverified.",
    "The GLB uses procedural materials only. No reference-photo textures, UV texture bake, independent scale survey, or verified WGS84 ground control has been applied.",
    "Do not publish this candidate to /map until independent measurements, reference-view review, geometry QA, georeference, and explicit human approval pass."
  ]
};
await writeFile(reportPath, JSON.stringify(candidate, null, 2) + "\n", "utf8");
console.log(JSON.stringify({
  modelPath: path.relative(root, modelPath),
  reportPath: path.relative(root, reportPath),
  bytes: glb.byteLength,
  sha256,
  triangleCount: report.geometryQuality?.triangleCount ?? null,
  structuralWarnings: report.geometryQuality?.warnings ?? [],
  reviewRequired: report.reviewRequired,
  mapReady: candidate.gates.mapReady,
  publicationEligible: candidate.gates.publicationEligible
}, null, 2));
